def form_xy(df, target, lead, flen, features, update_freq=1, start=None):
    """  Creates columns for input features (X) and targets (Y).

    Data frames are shifted so that all input features and targets are in the same row. Timestamp of the row is the
    forecast time.

    Parameters
    ----------
    df
    target
    lead
    flen
    features
    update_freq
    start

    Returns
    -------

    """

    # Drop duplicate index
    df = df[~df.index.duplicated(keep='first')]

    y_df = form_y(df, target, lead, flen, update_freq, start)
    x_df = form_x(df, target, features, update_freq, start)

    y_df = y_df.loc[y_df.index.intersection(x_df.index)]
    x_df = x_df.loc[x_df.index.intersection(y_df.index)]

    return x_df, y_df


def sincos_transform(df, max_value):
    sine = np.sin(2 * np.pi * df.iloc[:, 0].values / max_value)
    cosine = np.cos(2 * np.pi * df.iloc[:, 0].values / max_value)
    sincos = np.stack([sine, cosine], axis=-1)
    return sincos


