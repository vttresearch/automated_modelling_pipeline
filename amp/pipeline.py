    def _single_predict(self, df):
        pred_dict = self._target_predict(df)

        forecast = None
        for output, pred in pred_dict.items():
            if pred.count(axis='columns').any() > 1:
                raise ValueError('Forecast has overlapping values. Cannot produce single output')

            # Select the only value.
            pred[output] = pred.max(axis=1)
            if forecast is None:
                forecast = pred[[output]].copy()
            else:
                forecast[output] = pred[output]

        return forecast

    def _target_predict(self, df):
        input_df = df.copy()
        output_dict = {}

        for name, model in self._models.items():
            pred_dict = model.predict(input_df, output_mode='target')

            # copy the predictions into the input so that it can be used by the following model.
            for output, pred in pred_dict.items():
                columns = [f'{name}_{output}_{col}' for col in pred.columns]
                tmp_index = input_df.index.intersection(pred.index)
                input_df.loc[tmp_index, columns] = pred.loc[tmp_index, pred.columns].values

                output_name = self._output_map.get(f'{name}_{output}')
                if output_name is not None:
                    output_dict[output_name] = pred

        return output_dict

    def predict(self, input_df, output_mode='target'):

        if output_mode == 'single':
            pred = self._single_predict(input_df)
        elif output_mode == 'target':
            pred = self._target_predict(input_df)
        else:
            raise ValueError(f'Invalid output mode: {output_mode}')

        return pred

    def fit(self, df):
        input_df = df.copy()
        for name, model in self._models.items():

            model.fit(input_df)
            # todo how to divide the df so that the resulst do not overfit. Lets just accept the overfitting for now
            #  and think alternative solutions later.

            pred_dict = model.predict(input_df, output_mode='target')

            # copy the predictions into the input so that it can be used by the following model.
            for output, pred in pred_dict.items():
                columns = [f'{name}_{output}_{col}' for col in pred.columns]
                tmp_index = input_df.index.intersection(pred.index)
                input_df.loc[tmp_index, columns] = pred.loc[tmp_index, pred.columns].values

    def save(self, filename):
        if str(filename)[-4:] != '.zip':
            warnings.warn('Invalid file format for the model. Only zip supported.')
            filename = str(filename) + '.zip'

        model_files = {}
        models_tmp = deepcopy(self._models)

        # Save the individual models
        for m_name, model in self._models.items():
            model_file = f'{str(filename)[:-4]}_{m_name}_model.zip'
            model.save(model_file)
            model_files[f'{m_name}_model.zip'] = model_file
            # In order to save the Pipeline, the models need to be removed as they might contain non pickable parts.
            self._models[m_name] = type(model)

        #self._models = {}
        pickle_file = f'{str(filename)[:-4]}.pkl'
        joblib.dump(self, pickle_file)
        model_files['main.pkl'] = pickle_file
        self._models = models_tmp

        # Add all files to a zip file.
        with zipfile.ZipFile(filename, 'w') as zip_file:
            for name, m_file in model_files.items():
                zip_file.write(m_file, arcname=name)

        # Remove the original files.
        for m_file in model_files.values():
            os.remove(m_file)

    @classmethod
    def load(self, filename):
        if str(filename)[-4:] != '.zip':
            warnings.warn('Invalid file format for the model. Only zip supported.')
            filename = str(filename) + '.zip'

        extracted_dir = Path(filename).parent.joinpath('extracted_files')

        # Extract the contents of the zip file
        with zipfile.ZipFile(filename, 'r') as zip_file:
            zip_file.extractall(extracted_dir)

        # Load the Forecaster object.
        pipeline = joblib.load(extracted_dir.joinpath('main.pkl'))

        # Load individual
        for m_name, model_type in pipeline._models.items():
            pipeline._models[m_name] = model_type.load(extracted_dir.joinpath(f'{m_name}_model.zip'))

        # Remove the extracted files.
        shutil.rmtree(extracted_dir)

        return pipeline
